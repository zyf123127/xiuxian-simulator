bad = {}
for key, t in TEXTS.items():
    for ch in t:
        if ch in ("{", "}"):
            continue
        if ord(ch) > 127 and cmap.get(ord(ch)) is None:
            bad.setdefault(key, []).append(ch)

if bad:
    print("MISSING:")
    for k, v in bad.items():
        print(" ", k, "->", "".join(sorted(set(v))))
else:
    print("ALL OK: 新文案全部字符在字库内")

