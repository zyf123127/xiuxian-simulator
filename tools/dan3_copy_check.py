BS = chr(92)
ESC = {'n': '\n', 't': '\t', 'r': '\r', '"': '"', BS: BS, "'": "'", '0': '\0'}


def dec(raw):
    if BS not in raw:
        return raw
    out = []
    k = 0
    while k < len(raw):
        c = raw[k]
        if c != BS:
            out.append(c)
            k += 1
            continue
        k += 1
        out.append(ESC[raw[k]])
        k += 1
    return ''.join(out)


